"""Render input adapters from a service's reachable Smithy shapes."""

import keyword
from collections.abc import Callable, Mapping

from .smithy import SmithyMember, SmithyShape, to_snake_case

_KINDS = {
    "string": "string", "enum": "string", "timestamp": "string",
    "byte": "integer", "short": "integer", "integer": "integer",
    "long": "integer", "bigInteger": "integer",
    "float": "float", "double": "float", "bigDecimal": "float",
    "boolean": "boolean", "blob": "blob", "document": "document",
    "structure": "structure", "union": "union", "list": "sequence",
    "set": "sequence", "map": "map",
}


def render_input_adapters(
    shapes: Mapping[str, SmithyShape],
    targets: set[str],
    annotation: Callable[[str], str],
    field_name: Callable[[SmithyShape, SmithyMember], str],
) -> str:
    selected = sorted((shapes[target] for target in targets), key=lambda shape: shape.shape_id)
    lines = [
        "# Generated by rboto-codegen. DO NOT EDIT.",
        '"""Typed adapters for reusing values as service inputs."""',
        "from __future__ import annotations",
        "",
        "import builtins as _builtins",
        "from collections.abc import AsyncIterator as _AsyncIterator, Sequence as _Sequence",
        "from rboto.inputs import (",
        "    EnumInputAdapter as _EnumInputAdapter, InputAdapter as _InputAdapter,",
        "    _Member, _Schema, _Shape,",
        ")",
        "from . import types as _types",
        "",
        "_schema = _Schema({",
    ]
    for shape in selected:
        if shape.kind not in _KINDS:
            raise ValueError(f"unsupported input adapter shape: {shape.shape_id} ({shape.kind})")
        options = [repr(_KINDS[shape.kind])]
        if shape.kind in {"structure", "union"}:
            members = ", ".join(
                f"{field_name(shape, member)!r}: _Member({member.target!r}, {member.required!r})"
                for member in shape.members
                if member.target not in shapes or not shapes[member.target].error
            )
            options.append(f"members={{{members}}}")
        if shape.member_target or shape.value_target:
            options.append(f"item={shape.member_target or shape.value_target!r}")
        if shape.key_target:
            options.append(f"key={shape.key_target!r}")
        if shape.enum_values:
            options.append(f"values={shape.enum_values!r}")
        if shape.sparse:
            options.append("sparse=True")
        if shape.streaming:
            options.append("streaming=True")
        lines.append(f"    {shape.shape_id!r}: _Shape({', '.join(options)}),")
    lines.extend(["})", ""])
    reserved: set[str] = set()
    for shape in selected:
        name = to_snake_case(shape.name)
        if name.startswith("_"):
            name = "shape" + name
        if keyword.iskeyword(name):
            name += "_"
        while name in reserved:
            name += "_value"
        reserved.add(name)
        adapter = "_EnumInputAdapter" if shape.enum_values else "_InputAdapter"
        lines.append(
            f"{name}: {adapter}[{annotation(shape.shape_id)}] = "
            f"{adapter}(_schema, {shape.shape_id!r})"
        )
    return "\n".join(lines) + "\n"
